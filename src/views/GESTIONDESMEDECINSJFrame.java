    private void chargerMedecin() {
    MedecinJpaController dao = new MedecinJpaController();
    List<Medecin> liste = dao.listerTous();
    DefaultTableModel model = (DefaultTableModel) tableMedecin.getModel();
    model.setRowCount(0);
    for (Medecin m : liste) {
        model.addRow(new Object[]{
            m.getIdMedecin(), m.getNomMedecin(),
            m.getPrenomMedecin(), m.getSpecialite(),
            m.getEmailMedecin()
        });
    }
}


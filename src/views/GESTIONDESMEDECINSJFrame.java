    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (txtNomMedecin.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Le nom est obligatoire.", "Erreur", JOptionPane.ERROR_MESSAGE);
    return;
}
MedecinJpaController dao = new MedecinJpaController();
Medecin m = new Medecin();
m.setIdMedecin(txtIdMedecin.getText().trim());
m.setNomMedecin(txtNomMedecin.getText().trim());
m.setPrenomMedecin(txtPrenomMedecin.getText().trim());
m.setSpecialite(txtSpecialite.getText().trim());
m.setEmailMedecin(txtEmailMedecin.getText().trim());
if (dao.inserer(m)) {
    JOptionPane.showMessageDialog(this, "Médecin enregistré !");
    chargerMedecin();
    viderChamps();
} else {
    JOptionPane.showMessageDialog(this, "Erreur enregistrement.", "Erreur", JOptionPane.ERROR_MESSAGE);
}
        
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
        // TODO add your handling code here:
        int ligne = tableMedecin.getSelectedRow();
if (ligne < 0) {
    JOptionPane.showMessageDialog(this, "Sélectionnez un médecin.", "Erreur", JOptionPane.ERROR_MESSAGE);
    return;
}
String id = tableMedecin.getValueAt(ligne, 0).toString();
MedecinJpaController dao = new MedecinJpaController();
Medecin m = dao.trouverParId(id);
if (m == null) {
    JOptionPane.showMessageDialog(this, "Médecin introuvable.", "Erreur", JOptionPane.ERROR_MESSAGE);
    return;
}
m.setNomMedecin(txtNomMedecin.getText().trim());
m.setPrenomMedecin(txtPrenomMedecin.getText().trim());
m.setSpecialite(txtSpecialite.getText().trim());
m.setEmailMedecin(txtEmailMedecin.getText().trim());
if (dao.modifier(m)) {
    JOptionPane.showMessageDialog(this, "Médecin modifié !");
    chargerMedecin();
    viderChamps();
} else {
    JOptionPane.showMessageDialog(this, "Erreur modification.", "Erreur", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton6ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        int ligne = tableMedecin.getSelectedRow();
if (ligne < 0) {
    JOptionPane.showMessageDialog(this, "Sélectionnez un médecin.", "Erreur", JOptionPane.ERROR_MESSAGE);
    return;
}
String id     = tableMedecin.getValueAt(ligne, 0).toString();
String nom    = tableMedecin.getValueAt(ligne, 1).toString();
String prenom = tableMedecin.getValueAt(ligne, 2).toString();
int rep = JOptionPane.showConfirmDialog(this,
    "Supprimer Dr. " + prenom + " " + nom + " ?",
    "Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
if (rep == JOptionPane.YES_OPTION) {
    MedecinJpaController dao = new MedecinJpaController();
    if (dao.supprimer(id)) {
        JOptionPane.showMessageDialog(this, "Médecin supprimé !");
        chargerMedecin();
        viderChamps();
    } else {
        JOptionPane.showMessageDialog(this, "Impossible de supprimer.", "Erreur", JOptionPane.ERROR_MESSAGE);
    }
}
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String terme = txtRechercher.getText().trim();
if (terme.isEmpty()) {
    chargerMedecin();
    return;
}
MedecinJpaController dao = new MedecinJpaController();
List<Medecin> liste = dao.rechercherParNom(terme);
DefaultTableModel model = (DefaultTableModel) tableMedecin.getModel();
model.setRowCount(0);
for (Medecin m : liste) {
    model.addRow(new Object[]{
        m.getIdMedecin(), m.getNomMedecin(),
        m.getPrenomMedecin(), m.getSpecialite(),
        m.getEmailMedecin()
    });
}
    }//GEN-LAST:event_jButton3ActionPerformed


    private void btnModifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifierActionPerformed
        // TODO add your handling code here:
         int ligne = tableUtilisateurs.getSelectedRow();
    if (ligne < 0) {
        JOptionPane.showMessageDialog(this, "Sélectionnez un utilisateur.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }
    String type = tableUtilisateurs.getValueAt(ligne, 0).toString();
    String id = tableUtilisateurs.getValueAt(ligne, 1).toString();

    if ("Patient".equals(type) || "Médecin".equals(type)) {
        JOptionPane.showMessageDialog(this,
            "Le rôle ne peut être modifié que pour les comptes du personnel (Secrétaire/Caissier/Administrateur).",
            "Non disponible", JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    String[] roles = {"Secrétaire", "Caissier", "Administrateur"};
    String nouveauRole = (String) JOptionPane.showInputDialog(this,
        "Nouveau rôle pour " + id + " :", "Modifier le rôle",
        JOptionPane.QUESTION_MESSAGE, null, roles, type);

    if (nouveauRole != null) {
        boolean succes = new controllers.PersonnelJpaController().modifierRole(id, nouveauRole);
        if (succes) {
            JOptionPane.showMessageDialog(this, "Rôle modifié.");
            chargerUtilisateurs();
        } else {
            JOptionPane.showMessageDialog(this, "Erreur lors de la modification.", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnModifierActionPerformed

    private void btnSupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSupprimerActionPerformed
        // TODO add your handling code here:
        int ligne = tableUtilisateurs.getSelectedRow();
    if (ligne < 0) {
        JOptionPane.showMessageDialog(this, "Sélectionnez un utilisateur.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }
    String type = tableUtilisateurs.getValueAt(ligne, 0).toString();
    String id = tableUtilisateurs.getValueAt(ligne, 1).toString();

    int rep = JOptionPane.showConfirmDialog(this,
        "Supprimer le compte " + id + " (" + type + ") ?",
        "Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
    if (rep != JOptionPane.YES_OPTION) return;

    boolean succes;
    if ("Patient".equals(type)) {
        succes = new controllers.PatientJpaController().supprimer(id);
    } else if ("Médecin".equals(type)) {
        succes = new controllers.MedecinJpaController().supprimer(id);
    } else {
        succes = new controllers.PersonnelJpaController().supprimer(id);
    }

    if (succes) {
        JOptionPane.showMessageDialog(this, "Compte supprimé.");
        chargerUtilisateurs();
    } else {
        JOptionPane.showMessageDialog(this,
            "Impossible de supprimer : ce compte a probablement des consultations/paiements/factures liés.",
            "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSupprimerActionPerformed


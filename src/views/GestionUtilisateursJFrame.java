    private void chargerUtilisateurs() {
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new String[]{"Type", "ID", "Nom", "Email"}, 0
    );

    for (entities.Patient p : new controllers.PatientJpaController().listerTous()) {
        model.addRow(new Object[]{"Patient", p.getIdPatient(), p.getNomPatient(), p.getEmailPatient()});
    }
    for (entities.Medecin m : new controllers.MedecinJpaController().listerTous()) {
        model.addRow(new Object[]{"Médecin", m.getIdMedecin(), m.getNomMedecin(), m.getEmailMedecin()});
    }
    for (entities.Personnel per : new controllers.PersonnelJpaController().listerTous()) {
        model.addRow(new Object[]{per.getRole(), per.getIdPersonnel(), per.getNomPersonnel(), per.getEmailPersonnel()});
    }

    tableUtilisateurs.setModel(model);
}

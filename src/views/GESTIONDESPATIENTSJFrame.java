     private void chargerPatient() {
    try {
        PatientJpaController controller = new PatientJpaController();
        List<Patient> liste = controller.listerTous();

        DefaultTableModel model = (DefaultTableModel) tablePatient.getModel();
        model.setRowCount(0);

        for (Patient p : liste) {
            model.addRow(new Object[]{
                p.getIdPatient(),
                p.getNomPatient(),
                p.getPrenomPatient(),
                p.getAge(),
                p.getTelephone(),
                p.getEmailPatient()
            });
        }

        System.out.println("Patients chargés : " + liste.size());

    } catch (Exception e) {
        System.out.println("ERREUR : " + e.getMessage());
        e.printStackTrace();
    }
}
    
  


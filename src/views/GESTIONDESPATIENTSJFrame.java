        private void actionEnregistrer() { 
    if (txtNomPatient.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Le nom du patient est obligatoire.", 
            "Erreur", JOptionPane.ERROR_MESSAGE);
        txtNomPatient.requestFocus();
        return;
    }
    if (txtPrenomPatient.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Le prénom est obligatoire.", 
            "Erreur", JOptionPane.ERROR_MESSAGE);
        txtPrenomPatient.requestFocus();
        return;
    }
    try {
        Patient p = new Patient();
        p.setNomPatient(txtNomPatient.getText().trim());
        p.setPrenomPatient(txtPrenomPatient.getText().trim());
        p.setAge(Integer.parseInt(txtAge.getText().trim()));
        p.setTelephone(txtTelephone.getText().trim());
        p.setEmailPatient(txtEmailPatient.getText().trim());
        PatientJpaController dao = new PatientJpaController();
        if (dao.inserer(p)) {
            JOptionPane.showMessageDialog(this, "Patient enregistré !");
            chargerPatient();
            viderChamps();
        } else {
            JOptionPane.showMessageDialog(this, 
                "Erreur enregistrement.", 
                "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, 
            "L'âge doit être un nombre.", 
            "Erreur", JOptionPane.ERROR_MESSAGE);
    }
} 
